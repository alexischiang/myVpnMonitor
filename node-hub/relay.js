// Relay machines: a VPS running realm that forwards one port per (node, relay) entry to the node's
// landing machine, prepending a PROXY protocol v2 header so the node sees the user's address.
// The relay pulls its rules from node-hub (relay-install.sh sets up the timer); this module renders
// those rules as realm TOML and the one-line install command shown in the admin.
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const INSTALL_SCRIPT = fs.readFileSync(path.join(__dirname, "relay-install.sh"), "utf8");
const CONFIG_PATH = "/api/v1/server/relay/config";
const INSTALL_PATH = "/api/v1/server/relay/install.sh";

function hostPort(host, port) {
  return `${String(host).includes(":") ? `[${host}]` : host}:${Number(port)}`;
}

/**
 * The forwarding a relay's realm acts on: each listen port and where it forwards to, nothing for a
 * disabled relay. Relay and node names, notes and the relay's public address are not part of it.
 */
function realmRules(relay, endpoints) {
  if (!relay.isActive) return [];
  return endpoints.map(endpoint => ({ nodeId: Number(endpoint.nodeId), listenPort: Number(endpoint.listenPort), remote: hostPort(endpoint.remoteHost, endpoint.remotePort) }))
    .sort((a, b) => a.listenPort - b.listenPort);
}

/** True when an edit changes what realm forwards, i.e. when the relay's sync will rewrite its config and restart realm. */
function realmRulesChanged(beforeRelay, afterRelay, beforeEndpoints, afterEndpoints = beforeEndpoints) {
  return JSON.stringify(realmRules(beforeRelay, beforeEndpoints)) !== JSON.stringify(realmRules(afterRelay, afterEndpoints));
}

/**
 * realm TOML for a relay. No endpoints means realm is stopped (relay-install.sh checks for [[endpoints]]).
 * The sync restarts realm whenever the file changes byte for byte, so the file is rendered from
 * realmRules alone (comments carry ids only): renaming a node or a relay, or editing its notes,
 * must not drop every connection on the relay.
 */
function realmConfig(relay, endpoints) {
  const lines = [
    `# Generated by node-hub for relay ${relay.id}. Do not edit: the next sync overwrites it.`,
    "[log]",
    'level = "warn"',
    "",
    "[network]",
    "no_tcp = false",
    "use_udp = false",
    "send_proxy = true",
    "send_proxy_version = 2"
  ];
  for (const rule of realmRules(relay, endpoints)) {
    lines.push("", `# node ${rule.nodeId}`, "[[endpoints]]", `listen = "${hostPort("0.0.0.0", rule.listenPort)}"`, `remote = "${rule.remote}"`);
  }
  return `${lines.join("\n")}\n`;
}

/** Short hash of a config; the relay reports the hash of the file it applied, so the admin can tell when it caught up. */
function configHash(text) {
  return crypto.createHash("sha256").update(text).digest("hex").slice(0, 16);
}

function relayInstallCommand({ publicUrl, relay }) {
  if (!publicUrl) return "";
  const base = publicUrl.replace(/\/+$/, "");
  return `curl -fsSL ${base}${INSTALL_PATH} | sudo bash -s -- --hub ${base} --relay-id ${relay.id} --token ${relay.token}`;
}

module.exports = { realmConfig, realmRulesChanged, configHash, relayInstallCommand, INSTALL_SCRIPT, CONFIG_PATH, INSTALL_PATH };
